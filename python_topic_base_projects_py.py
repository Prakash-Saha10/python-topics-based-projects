import re
from collections import Counter

def text_extractor_project():

    # Sample text
    text = """
    Contact us at support@company.com or sales@company.com
    Call us at 123-456-7890 or 098-765-4321
    Visit on 25/10/2025 or 30/12/2025
    #python #coding #learning
    Important: URGENT task must be done ASAP!
    """

    # Extract emails
    email_pattern = r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b'
    emails = re.findall(email_pattern, text)
    print(f" Emails found: {emails}")

    # Extract phone numbers
    phone_pattern = r'\b\d{3}-\d{3}-\d{4}\b'
    phones = re.findall(phone_pattern, text)
    print(f" Phones found: {phones}")

    # Extract dates
    date_pattern = r'\b\d{2}/\d{2}/\d{4}\b'
    dates = re.findall(date_pattern, text)
    print(f"Dates found: {dates}")

    # Extract hashtags
    hashtag_pattern = r'#\w+'
    hashtags = re.findall(hashtag_pattern, text)
    print(f" Hashtags found: {hashtags}")

    # Extract capital words
    capital_words = re.findall(r'\b[A-Z]{2,}\b', text)
    print(f" Capital words: {capital_words}")

    # Word frequency using Counter
    words = re.findall(r'\b\w+\b', text.lower())
    word_counts = Counter(words)
    print(f"\n Most common words:")
    for word, count in word_counts.most_common(5):
        print(f"   {word}: {count}")

    # Count hashtags
    hashtag_counts = Counter(hashtags)
    print(f"\n Hashtag counts: {hashtag_counts}")

    # Replace pattern
    censored = re.sub(r'\d{3}-\d{3}-\d{4}', '[REDACTED]', text)
    print(f"\n Censored text (phones hidden):")
    print(censored[:100] + "...")

