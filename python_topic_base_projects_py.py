import time
from functools import wraps

def timing_decorator_project():
    # Basic decorator
    def timer(func):
        """Measure function execution time"""
        @wraps(func)
        def wrapper(*args, **kwargs):
            start = time.time()
            result = func(*args, **kwargs)
            end = time.time()
            print(f" {func.__name__} took {end - start:.4f}s")
            return result
        return wrapper

    # Decorator with logging
    def logger(func):
        """Log function calls"""
        @wraps(func)
        def wrapper(*args, **kwargs):
            print(f"Calling {func.__name__}()")
            result = func(*args, **kwargs)
            print(f"{func.__name__}() completed")
            return result
        return wrapper

    # Decorator for validation
    def validate_positive(func):
        """Validate positive numbers"""
        @wraps(func)
        def wrapper(n):
            if n < 0:
                raise ValueError("Number must be positive")
            return func(n)
        return wrapper

    # Using decorators
    @timer
    def slow_function():
        """Simulate slow operation"""
        time.sleep(0.1)
        return "Done"

    @logger
    @timer
    def calculate_sum(n):
        """Calculate sum with multiple decorators"""
        time.sleep(0.05)
        return sum(range(n))

    @validate_positive
    def square_root(n):
        """Calculate square root"""
        return n ** 0.5

    # Test decorated functions
    print("Testing decorated functions:\n")

    result1 = slow_function()
    print(f"Result: {result1}\n")

    result2 = calculate_sum(1000)
    print(f"Sum: {result2}\n")

    try:
        result3 = square_root(16)
        print(f"√16 = {result3}")
        result4 = square_root(-4)  # Will raise error
    except ValueError as e:
        print(f"Error: {e}")

    # Decorator with arguments
    def repeat(times):
        """Decorator that repeats function"""
        def decorator(func):
            @wraps(func)
            def wrapper(*args, **kwargs):
                results = []
                for _ in range(times):
                    result = func(*args, **kwargs)
                    results.append(result)
                return results
            return wrapper
        return decorator

    @repeat(times=3)
    def greet(name):
        """Greet someone"""
        return f"Hello, {name}!"

    print(f"\nRepeated greeting: {greet('Alice')}")

