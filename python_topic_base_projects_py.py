def safe_calculator_project():
    # Basic try-except
    def safe_divide(a, b):
        """Divide with error handling"""
        try:
            result = a / b
            return result
        except ZeroDivisionError:
            print(" Error: Cannot divide by zero!")
            return None
        except TypeError:
            print("Error: Invalid input types!")
            return None

    print(f"10 / 2 = {safe_divide(10, 2)}")
    print(f"10 / 0 = {safe_divide(10, 0)}")

    # Try-except-else
    def safe_sqrt(n):
        """Square root with validation"""
        try:
            if n < 0:
                raise ValueError("Cannot calculate square root of negative number")
            result = n ** 0.5
        except ValueError as e:
            print(f" Error: {e}")
            return None
        else:
            print(f" Calculation successful")
            return result

    print(f"√16 = {safe_sqrt(16)}")
    print(f"√-4 = {safe_sqrt(-4)}")

    # Try-except-finally
    def read_number_from_file(filename):
        """Read with cleanup"""
        try:
            f = open(filename, 'r')
            content = f.read()
            number = int(content)
            return number
        except FileNotFoundError:
            print(f" File {filename} not found")
            return None
        except ValueError:
            print(f" File content is not a number")
            return None
        finally:
            print(f"Cleanup: Attempted to read {filename}")
            try:
                f.close()
            except:
                pass

    # Custom exception
    class NegativeNumberError(Exception):
        """Custom exception for negative numbers"""
        pass

    def positive_only(n):
        """Only accept positive numbers"""
        try:
            if n < 0:
                raise NegativeNumberError(f"Number {n} is negative!")
            return n * 2
        except NegativeNumberError as e:
            print(f" {e}")
            return None

    print(f"5 * 2 = {positive_only(5)}")
    print(f"-3 * 2 = {positive_only(-3)}")

    # Multiple exceptions
    def safe_operation(a, b, operation):
        """Perform operation safely"""
        try:
            if operation == "divide":
                return a / b
            elif operation == "power":
                return a ** b
            else:
                raise ValueError(f"Unknown operation: {operation}")
        except ZeroDivisionError:
            return "Error: Division by zero"
        except OverflowError:
            return "Error: Result too large"
        except ValueError as e:
            return f"Error: {e}"
        except Exception as e:
            return f"Unexpected error: {e}"

    print(f"10 / 2 = {safe_operation(10, 2, 'divide')}")
    print(f"10 / 0 = {safe_operation(10, 0, 'divide')}")
    print(f"999 ** 999 = {safe_operation(999, 999, 'power')}")

