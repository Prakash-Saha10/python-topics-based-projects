def vehicle_system_project():
  class Vehicle:
        """Base vehicle class"""

        def __init__(self, brand, model, year):
            self._brand = brand  # Protected
            self.__model = model  # Private
            self._year = year

        @property
        def brand(self):
            """Property getter"""
            return self._brand

        @brand.setter
        def brand(self, value):
            """Property setter with validation"""
            if len(value) < 2:
                raise ValueError("Brand must be at least 2 characters")
            self._brand = value

        @property
        def model(self):
            """Getter for private attribute"""
            return self.__model

        def get_info(self):
            """Method to be overridden"""
            return f"{self._year} {self._brand} {self.__model}"

        def start(self):
            """Common method"""
            return "Vehicle started"

    # Inheritance - Car
  class Car(Vehicle):
        """Car inherits from Vehicle"""

        def __init__(self, brand, model, year, doors):
            super().__init__(brand, model, year)
            self.doors = doors

        def get_info(self):
            """Override parent method - Polymorphism"""
            base_info = super().get_info()
            return f" Car: {base_info}, {self.doors} doors"

        def start(self):
            """Override with different behavior"""
            return "Car engine started with key"

    # Inheritance - Motorcycle
  class Motorcycle(Vehicle):
        """Motorcycle inherits from Vehicle"""

        def __init__(self, brand, model, year, engine_cc):
            super().__init__(brand, model, year)
            self.engine_cc = engine_cc

        def get_info(self):
            """Override parent method - Polymorphism"""
            base_info = super().get_info()
            return f"  Motorcycle: {base_info}, {self.engine_cc}cc"

        def start(self):
            """Override with different behavior"""
            return "Motorcycle started with kick"

    # Create objects
  car = Car("Toyota", "Camry", 2024, 4)
  bike = Motorcycle("Honda", "CBR", 2024, 1000)

    # Polymorphism - same method, different behavior
  vehicles = [car, bike]

  print("Vehicle Information:")
  for vehicle in vehicles:
        print(f"  {vehicle.get_info()}")
        print(f"  {vehicle.start()}")

    # Property usage
  print(f"\nCar brand: {car.brand}")
  car.brand = "Honda"
  print(f"Updated brand: {car.brand}")

    # Accessing through property
  print(f"Car model: {car.model}")

